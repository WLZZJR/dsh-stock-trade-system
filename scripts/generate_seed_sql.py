#!/usr/bin/env python3
"""Regenerate database/seeds/01_currencies.sql and 02_countries.sql from the upstream lists.

Run by hand when the reference lists change; the generated SQL is committed so that normal
builds and CI never need network access. Usage:

    python scripts/generate_seed_sql.py <iso4217-list-one.xml> <iso3166-1.json> <retrieved-date>
"""

import json
import sys
import xml.etree.ElementTree as ET  # noqa: S405 - trusted, locally downloaded reference file
from pathlib import Path

SEEDS = Path(__file__).resolve().parents[1] / "database" / "seeds"


def quote(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def currencies(xml_path: Path) -> tuple[str, list[tuple[str, str, int]]]:
    root = ET.parse(xml_path).getroot()  # noqa: S314
    published = root.attrib["Pblshd"]
    rows: dict[str, tuple[str, int]] = {}
    for entry in root.iter("CcyNtry"):
        code, name, minor = (
            entry.findtext("Ccy"),
            entry.findtext("CcyNm"),
            entry.findtext("CcyMnrUnts"),
        )
        if not code or not name or minor is None or not minor.isdigit():
            continue  # no code (e.g. Antarctica) or no numeric minor unit (metals, XXX, XDR, ...)
        rows.setdefault(code, (name, int(minor)))
    return published, [(c, n, m) for c, (n, m) in sorted(rows.items())]


def write_currencies(xml_path: Path, retrieved: str) -> None:
    published, rows = currencies(xml_path)
    values = ",\n".join(f"  ({quote(c)}, {quote(n)}, {m})" for c, n, m in rows)
    header = (
        "-- ISO 4217 currencies with a numeric minor unit (metals, funds without one, XXX, XDR\n"
        "-- and similar codes are intentionally excluded).\n"
        "-- Source: SIX Group, ISO 4217 maintenance agency, list-one.xml "
        f"(published {published})\n"
        "--   https://www.six-group.com/dam/download/financial-information/data-center/"
        "iso-currrency/lists/list-one.xml\n"
        f"-- Retrieved: {retrieved}. Generated by scripts/generate_seed_sql.py; "
        "do not edit by hand.\n"
        f"-- Rows: {len(rows)}\n"
    )
    sql = (
        f"{header}INSERT INTO currencies (code, name, minor_unit) VALUES\n{values}\n"
        "ON CONFLICT (code) DO NOTHING;\n"
    )
    (SEEDS / "01_currencies.sql").write_text(sql, encoding="utf-8", newline="\n")


def write_countries(json_path: Path, retrieved: str) -> None:
    data = json.loads(json_path.read_text(encoding="utf-8"))["3166-1"]
    rows = sorted((c["alpha_2"], c["alpha_3"], c["numeric"], c["name"]) for c in data)
    values = ",\n".join(
        f"  ({quote(a2)}, {quote(a3)}, {quote(num)}, {quote(name)})" for a2, a3, num, name in rows
    )
    header = (
        "-- ISO 3166-1 country codes.\n"
        "-- Source: Debian iso-codes project (data/iso_3166-1.json, LGPL-2.1-or-later data)\n"
        "--   https://salsa.debian.org/iso-codes-team/iso-codes\n"
        f"-- Retrieved: {retrieved}. Generated by scripts/generate_seed_sql.py; "
        "do not edit by hand.\n"
        f"-- Rows: {len(rows)}\n"
    )
    sql = (
        f"{header}INSERT INTO countries (code, alpha3, numeric_code, name) VALUES\n{values}\n"
        "ON CONFLICT (code) DO NOTHING;\n"
    )
    (SEEDS / "02_countries.sql").write_text(sql, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    xml_file, json_file, retrieved_on = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
    write_currencies(xml_file, retrieved_on)
    write_countries(json_file, retrieved_on)
